# Sets "executable": True/False for each activity depending on:
# 1) whether preconditions are satisfied
# 2) whether we are within the correct time window for the activity
#
# Arbitration layer: combines Event Planner signals (criticality/priority)
# with Plan Validator signals (preconditions/time) to produce an
# "arbitrated_status" for each activity:
#   EXECUTABLE            -> ready to perform
#   BLOCKED_CRITICAL      -> critical activity, cannot execute, needs recovery
#   BLOCKED_NON_CRITICAL  -> non-critical activity, cannot execute, can wait
#   DEFERRED              -> blocked by time window only, may become executable later
#
# For BLOCKED_CRITICAL activities, "recovery_actions" lists canonical actions
# whose effects satisfy the missing preconditions, so the system can proactively
# unblock critical activities.

import os
from datetime import date, datetime
from typing import List, Dict, Any, TYPE_CHECKING
from planning.canonical_actions import CANONICAL_ACTIONS
from utils.logs import log_graph_state, log_message
from utils.structured_logs import (
    log_precondition_check,
    log_temporal_check,
    log_arbitration,
    log_structured,
)
from deterministic.activity_planner import TOLERANCE_START_TIME_ACTIVITY
from colorama import Fore, Style

if TYPE_CHECKING:
    from graph.graph_init import GraphState

# Common stopwords to ignore when comparing activity name vs canonical action
_STOPWORDS = frozenset({
    "a", "an", "the", "take", "do", "some", "my", "with", "for",
    "and", "or", "to", "in", "on", "at", "is", "it", "this",
})

# Known contradictory fact pairs for invariant validation
_INVARIANT_PAIRS = [
    ("patient_awake", "patient_sleeping"),
    ("patient_tired", "patient_not_tired"),
    ("patient_sad", "patient_emotionally_stable"),
]


def _check_activity_canonical_consistency(
    activity_name: str,
    canonical_action: str,
) -> bool:
    """Check if activity name shares any meaningful keyword with the
    canonical action name or its description.

    Returns True if there is at least one overlapping keyword,
    False if the mapping looks suspicious.
    """
    if not canonical_action or canonical_action == "unknown":
        return True  # Skip check for unknown actions

    action_def = CANONICAL_ACTIONS.get(canonical_action, {})
    description = action_def.get("description", "")
    aliases = action_def.get("aliases", [])

    # Build keyword sets (lowercase, stopwords removed, len > 2)
    name_words = {
        w.lower() for w in activity_name.replace("_", " ").split()
        if len(w) > 2 and w.lower() not in _STOPWORDS
    }
    canon_words = {
        w.lower() for w in canonical_action.replace("_", " ").split()
        if len(w) > 2 and w.lower() not in _STOPWORDS
    }
    desc_words = {
        w.lower() for w in description.replace("_", " ").split()
        if len(w) > 2 and w.lower() not in _STOPWORDS
    }

    # A correct mapping can share no word with the action identifier:
    # "Take Vitamin D" against take_medication / "Take prescribed
    # medication" overlaps on nothing once "take" is dropped as a
    # stopword. The alias list carries the everyday vocabulary patients
    # use, so the warning fires on genuinely unrelated mappings only.
    alias_words = {
        word.lower()
        for alias in aliases
        for word in alias.replace("_", " ").split()
        if len(word) > 2 and word.lower() not in _STOPWORDS
    }

    all_canon_words = canon_words | desc_words | alias_words
    overlap = name_words & all_canon_words
    return len(overlap) > 0


_DATE_FORMATS = ("%d-%m-%Y", "%d/%m/%Y", "%Y-%m-%d")


def _split_date(text: str) -> tuple[date | None, str]:
    """Separate a leading calendar date from the time, if there is one.

    When the patient postpones an activity, the regenerated task can move it
    to another day by writing a date into its time ("17-09-2026 10:00").
    """
    parts = text.split()
    if len(parts) == 2:
        for fmt in _DATE_FORMATS:
            try:
                return datetime.strptime(parts[0], fmt).date(), parts[1]
            except ValueError:
                continue
    return None, text


def _parse_activity_time(
    activity_time: str, reference_date: date | None = None
) -> datetime | None:
    """Parse a scheduled time, accepting the shapes the synthesizer emits.

    The task is generated by an LLM, so the same 9am can arrive as "09:00",
    "9:00", "9.00" or "0900". Normalising them here removes blocking
    reasons that are about formatting rather than about the schedule;
    anything still unparseable stays fail-closed. A time carrying a date is
    placed on that date, any other on reference_date (default: today).
    """
    text = str(activity_time).strip()
    if not text:
        return None
    on_date, text = _split_date(text)
    on_date = on_date or reference_date or datetime.today().date()
    text = text.replace(".", ":").replace("h", ":").upper()

    suffix = ""
    for marker in ("AM", "PM"):
        if text.endswith(marker):
            suffix = marker
            text = text[: -len(marker)].strip()
            break

    if ":" not in text and text.isdigit():
        if len(text) in (3, 4):
            text = f"{text[:-2]}:{text[-2:]}"
        elif len(text) in (1, 2):
            text = f"{text}:00"

    try:
        parsed = datetime.strptime(text, "%H:%M")
    except ValueError:
        return None

    hour = parsed.hour
    if suffix == "PM" and hour < 12:
        hour += 12
    elif suffix == "AM" and hour == 12:
        hour = 0

    return datetime.combine(on_date, parsed.time().replace(hour=hour))


def _validate_world_state_invariants(world_state: dict) -> list:
    """Check for contradictory facts in the world state.
    Returns a list of violation dicts.
    """
    violations = []
    for fact_a, fact_b in _INVARIANT_PAIRS:
        if world_state.get(fact_a, False) and world_state.get(fact_b, False):
            violations.append({
                "fact_a": fact_a,
                "fact_b": fact_b,
                "message": f"Both {fact_a} and {fact_b} are True (contradictory)",
            })
    return violations


def _find_recovery_actions(
    missing_preconditions: List[str],
    world_state: Dict[str, bool],
) -> List[Dict[str, Any]]:
    """
    Find canonical actions whose effects satisfy the missing preconditions.

    A recovery action is suggested if:
    - its effects include at least one missing precondition
    - its own preconditions are all satisfied in the current world state
      (i.e., the recovery action is itself executable right now)

    Returns a list of dicts with: canonical_action, description, satisfies
    """
    recovery = []
    for action_name, action_def in CANONICAL_ACTIONS.items():
        effects = set(action_def.get("effects", []))
        missing_covered = effects & set(missing_preconditions)

        if not missing_covered:
            continue

        # Check if the recovery action's own preconditions are satisfied
        action_preconditions = action_def.get("preconditions", [])
        preconditions_met = all(
            world_state.get(pre, False) for pre in action_preconditions
        )

        if preconditions_met:
            recovery.append(
                {
                    "canonical_action": action_name,
                    "description": action_def.get("description", action_name),
                    "satisfies": list(missing_covered),
                }
            )

    return recovery

def plan_validator_node(state: "GraphState"):

    print(Fore.GREEN + "[position: PLAN VALIDATOR NODE]" + Style.RESET_ALL)
    log_graph_state(state, "plan_validator_node")

    world_state = state.get("world_state", {})
    current_datetime = state.get("fake_datetime")

    if current_datetime is None:
        raise ValueError("fake_datetime is None in plan_validator_node")

    if state["updated_task"] is None:
        raise ValueError("Task is None in plan_validator_node")

    activities = state["updated_task"]["activities"]

    # --------------------------------------------------
    # VALIDATE WORLD STATE INVARIANTS
    # Check for contradictory facts (e.g. patient_awake=True + patient_sleeping=True)
    # --------------------------------------------------
    invariant_violations = _validate_world_state_invariants(world_state)
    if invariant_violations:
        for v in invariant_violations:
            print(
                Fore.YELLOW
                + f"[WARNING] World state invariant violated: {v['message']}"
                + Style.RESET_ALL
            )
            log_message(f"PLAN_VALIDATOR - invariant violation: {v['message']}")
            log_structured({
                "node": "plan_validator",
                "decision_type": "invariant_violation",
                "violation": v,
            })

    # The task is LLM-generated and sometimes lists the same activity at the
    # same time twice. A repeat at a *different* time is legitimate (two
    # medication rounds), so only an exact name+time repeat is redundant.
    seen_activities: set = set()

    for activity in activities:

        canonical_action = activity.get("canonical_action")

        executable = True

        not_executable_reasons = []

        duplicate_key = (
            str(activity.get("activity_name", "")).strip().lower(),
            str(activity.get("activity_time") or "").strip(),
        )
        is_duplicate = (
            duplicate_key in seen_activities and not activity.get("done", False)
        )
        seen_activities.add(duplicate_key)

        if is_duplicate:
            print(
                Fore.YELLOW
                + f"[WARNING] Activity '{activity['activity_name']}' is a "
                f"duplicate of an earlier entry at the same time."
                + Style.RESET_ALL
            )
            log_message(
                f"PLAN_VALIDATOR - duplicate activity: "
                f"'{activity['activity_name']}' at {duplicate_key[1] or 'no time'}"
            )
            log_structured({
                "node": "plan_validator",
                "decision_type": "duplicate_activity",
                "activity_name": activity.get("activity_name", ""),
                "activity_time": duplicate_key[1],
                "message": "Same activity name and time already present in the task",
            })
            executable = False
            not_executable_reasons.append("duplicate_activity")

        # --------------------------------------------------
        # SKIP DONE ACTIVITIES
        # Already-completed activities are not re-validated.
        # They are marked as EXECUTABLE (no action needed).
        # --------------------------------------------------

        if activity.get("done", False):
            activity["executable"] = True
            activity["not_executable_reasons"] = []
            activity["arbitrated_status"] = "EXECUTABLE"
            activity["recovery_actions"] = []
            log_arbitration(
                activity_name=activity["activity_name"],
                executable=True,
                not_executable_reasons=[],
                arbitrated_status="EXECUTABLE",
                is_critical=activity.get("critical", False),
                priority=activity.get("priority", 3),
                recovery_actions=[],
            )
            continue

        # --------------------------------------------------
        # CHECK PRECONDITIONS
        # --------------------------------------------------

        if not canonical_action or canonical_action == "unknown":

            # Fail-closed: action not recognized by the canonicalizer
            # or missing entirely. No preconditions can be verified,
            # so the activity is marked as non-executable for safety.
            print(
                f"Activity '{activity['activity_name']}' not executable: "
                f"unknown or missing canonical action"
            )
            executable = False
            not_executable_reasons.append("unknown_canonical_action")

        elif canonical_action not in CANONICAL_ACTIONS:

            # Fail-closed: canonical_action is a non-empty string that is
            # neither "unknown" nor a valid key in CANONICAL_ACTIONS.
            # This catches corrupted/invented canonical action names that
            # would otherwise bypass precondition checking entirely.
            print(
                f"Activity '{activity['activity_name']}' not executable: "
                f"canonical action '{canonical_action}' not in dictionary"
            )
            executable = False
            not_executable_reasons.append("unknown_canonical_action")

        elif canonical_action in CANONICAL_ACTIONS:

            preconditions = CANONICAL_ACTIONS[canonical_action]["preconditions"]
            preconditions_checked = []
            missing = []

            for precondition in preconditions:

                satisfied = world_state.get(precondition, False)
                preconditions_checked.append({
                    "precondition": precondition,
                    "satisfied": satisfied,
                })

                if not satisfied:

                    print(f"Activity '{activity['activity_name']}' not executable: precondition '{precondition}' not satisfied")
                    executable = False
                    missing.append(precondition)

                    not_executable_reasons.append(f"missing_precondition: {precondition}")

            log_precondition_check(
                activity_name=activity["activity_name"],
                canonical_action=canonical_action,
                preconditions_checked=preconditions_checked,
                all_satisfied=len(missing) == 0,
                missing=missing,
            )

        # --------------------------------------------------
        # CHECK TEMPORAL WINDOW
        # --------------------------------------------------

        activity_time = activity.get("activity_time")
        without_time = activity.get("without_time", False)

        if state["fake_datetime"] is None:
            raise ValueError("fake_datetime is None in plan_validator_node")

        current_time = state["fake_datetime"]
        reference_date = current_time.date()

        # --- Malformed / contradictory temporal flags (fail-closed) ---
        # F36: activity_time is an empty string (not None) -> malformed input
        # F37: activity_time is set AND without_time=True -> contradictory flags
        # In both cases the temporal signal is unreliable, so we block the
        # activity and log a structured warning rather than silently skipping
        # the temporal check.
        malformed_time = False
        if activity_time is not None and activity_time == "":
            print(
                f"Activity '{activity['activity_name']}' not executable: "
                f"activity_time is an empty string (malformed)"
            )
            executable = False
            not_executable_reasons.append("malformed_activity_time:empty_string")
            log_structured({
                "node": "plan_validator",
                "decision_type": "malformed_temporal_input",
                "activity_name": activity["activity_name"],
                "issue": "empty_string",
                "activity_time": activity_time,
                "without_time": without_time,
            })
            malformed_time = True
        elif activity_time and without_time:
            print(
                f"Activity '{activity['activity_name']}' not executable: "
                f"contradictory temporal flags (activity_time='{activity_time}' "
                f"but without_time=True)"
            )
            executable = False
            not_executable_reasons.append("contradictory_time_flags")
            log_structured({
                "node": "plan_validator",
                "decision_type": "malformed_temporal_input",
                "activity_name": activity["activity_name"],
                "issue": "contradictory_flags",
                "activity_time": activity_time,
                "without_time": without_time,
            })
            malformed_time = True

        if (activity_time and not without_time and not malformed_time):

            try:

                scheduled_time = _parse_activity_time(
                    activity_time, reference_date
                )
                if scheduled_time is None:
                    raise ValueError(f"unparseable activity_time {activity_time!r}")

                earliest_time = (scheduled_time - TOLERANCE_START_TIME_ACTIVITY)
                latest_time = (scheduled_time + TOLERANCE_START_TIME_ACTIVITY)



                if not (earliest_time <= current_time <= latest_time):

                    print(f"Activity '{activity['activity_name']}' not executable: outside time window ({activity_time})")

                    executable = False

                    if current_time > latest_time:
                        not_executable_reasons.append(f"outside_time_window_expired:{activity_time}")
                    else:
                        not_executable_reasons.append(f"outside_time_window_early:{activity_time}")

                log_temporal_check(
                    activity_name=activity["activity_name"],
                    activity_time=activity_time,
                    without_time=without_time,
                    within_window=earliest_time <= current_time <= latest_time,
                    earliest=earliest_time.strftime("%H:%M"),
                    latest=latest_time.strftime("%H:%M"),
                    current_time=current_time.strftime("%H:%M"),
                )

            except ValueError:

                print(f"Warning: invalid activity_time '{activity_time}' for activity '{activity['activity_name']}'")
                executable = False
                not_executable_reasons.append("invalid_activity_time")

        # --------------------------------------------------
        # CONSISTENCY CHECK: activity name vs canonical action
        # Detects potential wrong canonicalization by checking
        # keyword overlap between activity name and action description.
        # Does not block, but logs a warning.
        # --------------------------------------------------
        if canonical_action and canonical_action != "unknown" and canonical_action in CANONICAL_ACTIONS:
            is_consistent = _check_activity_canonical_consistency(
                activity["activity_name"], canonical_action
            )
            if not is_consistent:
                print(
                    Fore.YELLOW
                    + f"[WARNING] Activity '{activity['activity_name']}' mapped to "
                    f"canonical action '{canonical_action}' — no keyword overlap. "
                    f"Possible wrong canonicalization."
                    + Style.RESET_ALL
                )
                log_message(
                    f"PLAN_VALIDATOR - suspicious mapping: "
                    f"'{activity['activity_name']}' -> '{canonical_action}'"
                )
                log_structured({
                    "node": "plan_validator",
                    "decision_type": "suspicious_mapping",
                    "activity_name": activity["activity_name"],
                    "canonical_action": canonical_action,
                    "message": "No keyword overlap between activity name and canonical action",
                })

        # --------------------------------------------------
        # ARBITRATION: combine Event Planner signals (criticality/priority)
        # with Plan Validator signals (preconditions/time)
        # --------------------------------------------------

        is_critical = activity.get("critical", False)
        priority = activity.get("priority", 3)

        # Classify the type of block
        has_precondition_issues = any(
            "missing_precondition" in r for r in not_executable_reasons
        )
        has_time_issues = any(
            "outside_time_window" in r for r in not_executable_reasons
        )
        has_time_expired = any(
            "outside_time_window_expired" in r for r in not_executable_reasons
        )
        has_unknown_action = "unknown_canonical_action" in not_executable_reasons
        is_duplicate_only = not_executable_reasons == ["duplicate_activity"]

        if executable:
            arbitrated_status = "EXECUTABLE"
        elif is_duplicate_only:
            # A repeat of an entry already validated above: blocking it only
            # stops the robot proposing the same activity twice, so it never
            # calls for recovery, whatever its criticality.
            arbitrated_status = "BLOCKED_NON_CRITICAL"
        elif has_unknown_action:
            # Unknown action: no preconditions from which to compute a
            # recovery. A critical one is still flagged, since its status
            # alone would not tell the staff that a critical activity is
            # being refused.
            arbitrated_status = "BLOCKED_NON_CRITICAL"
            if is_critical:
                log_structured({
                    "node": "plan_validator",
                    "decision_type": "critical_unrecognized",
                    "activity_name": activity["activity_name"],
                    "canonical_action": canonical_action,
                    "message": (
                        "Critical activity refused because its action is "
                        "not recognized; staff attention needed"
                    ),
                })
        elif has_time_issues and not has_precondition_issues:
            # Blocked ONLY by time window
            if has_time_expired:
                # Past the window: activity is expired, won't become executable
                arbitrated_status = "BLOCKED_NON_CRITICAL"
            else:
                # Before the window: may become executable later
                arbitrated_status = "DEFERRED"
        elif is_critical:
            # Critical activity blocked by preconditions (possibly also time)
            arbitrated_status = "BLOCKED_CRITICAL"
        else:
            # Non-critical activity blocked by preconditions
            arbitrated_status = "BLOCKED_NON_CRITICAL"

        # --------------------------------------------------
        # RECOVERY ACTIONS: for BLOCKED_CRITICAL, find actions
        # that can satisfy the missing preconditions
        # --------------------------------------------------

        # No recovery once the window has passed: satisfying the missing
        # preconditions would not make the activity executable again.
        recovery_actions = []
        if arbitrated_status == "BLOCKED_CRITICAL" and not has_time_expired:
            missing_preconditions = [
                r.split(": ", 1)[1]
                for r in not_executable_reasons
                if "missing_precondition" in r
            ]
            recovery_actions = _find_recovery_actions(
                missing_preconditions, world_state
            )

            if recovery_actions:
                print(
                    Fore.YELLOW
                    + f"[ARBITRATION] Critical activity '"
                    f"{activity['activity_name']}' is blocked. "
                    f"Recovery actions available: "
                    f"{[r['canonical_action'] for r in recovery_actions]}"
                    + Style.RESET_ALL
                )
                log_message(
                    f"PLAN_VALIDATOR - recovery actions for critical "
                    f"activity '{activity['activity_name']}': "
                    f"{[r['canonical_action'] for r in recovery_actions]}"
                )
            else:
                print(
                    Fore.RED
                    + f"[ARBITRATION] Critical activity '"
                    f"{activity['activity_name']}' is blocked with "
                    f"NO recovery actions available. Manual intervention "
                    f"may be required."
                    + Style.RESET_ALL
                )
                log_message(
                    f"PLAN_VALIDATOR - critical activity '"
                    f"{activity['activity_name']}' blocked, no recovery "
                    f"actions available"
                )

        # --------------------------------------------------
        # SAVE RESULTS
        # --------------------------------------------------

        activity["executable"] = executable
        activity["not_executable_reasons"] = not_executable_reasons
        activity["arbitrated_status"] = arbitrated_status
        activity["recovery_actions"] = recovery_actions

        log_arbitration(
            activity_name=activity["activity_name"],
            executable=executable,
            not_executable_reasons=not_executable_reasons,
            arbitrated_status=arbitrated_status,
            is_critical=is_critical,
            priority=priority,
            recovery_actions=recovery_actions,
        )

    # Ablation arm of the replay: with VALIDATOR_DISABLED=true every activity
    # is passed on as executable, as in the base architecture, so Next Steps
    # sees nothing blocked and enforcement never fires. The decisions are
    # still computed and logged as what the validator would have done, so
    # the replies of this arm can be compared against them.
    if os.getenv("VALIDATOR_DISABLED", "false").strip().lower() == "true":
        for activity in activities:
            log_structured({
                "node": "plan_validator",
                "decision_type": "validator_disabled",
                "activity_name": activity.get("activity_name", ""),
                "canonical_action": activity.get("canonical_action"),
                "would_be_status": activity.get("arbitrated_status"),
                "would_be_reasons": activity.get("not_executable_reasons", []),
                "critical": activity.get("critical", False),
            })
            activity["executable"] = True
            activity["not_executable_reasons"] = []
            activity["arbitrated_status"] = "EXECUTABLE"
            activity["recovery_actions"] = []

    state["updated_task"]["activities"] = activities

    return state